/**
 * Klei 用户 ID 的字符集。
 *
 * `KU_` 之后是 base64url 风格的随机串，**含 `-`**（实测 `KU_3rpxG-xy`）。
 *
 * 此前六处各写一份 `^KU_[A-Za-z0-9_]{1,64}$`，把带 `-` 的真实账号判成非法 ID：
 * 在线列表把它标成「临时身份」并禁用封禁，加入名单、踢出也一律被拒——
 * 同一个账号在面板的不同环节里根本不像同一个人。统一到这里，只此一份。
 *
 * 这个字符集同时是「能不能安全拼进 Lua 命令」的判据：它不含引号、反斜杠、
 * 空格与控制字符，拼进字符串字面量不会逃逸。
 */

/** 不带锚点，供需要内嵌进更大正则的地方使用（如从日志行里抠出 ID） */
export const PLAYER_KU_ID_SOURCE = 'KU_[A-Za-z0-9_-]{1,64}'

/** 完整匹配一个 Klei 用户 ID */
export const PLAYER_KU_ID_PATTERN = new RegExp(`^${PLAYER_KU_ID_SOURCE}$`)
